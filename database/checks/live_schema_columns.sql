live AS (
    SELECT table_name::text AS table_name, column_name::text AS column_name,
           CASE data_type WHEN 'jsonb' THEN 'json' ELSE data_type::text END AS data_type
    FROM information_schema.columns
    WHERE table_schema = 'public'
)
SELECT 'MISSING COLUMN' AS finding, e.table_name, e.column_name, e.data_type AS in_models, NULL AS in_database
FROM expected e
LEFT JOIN live l ON l.table_name = e.table_name AND l.column_name = e.column_name
WHERE l.column_name IS NULL
UNION ALL
SELECT 'TYPE DIFFERS', e.table_name, e.column_name, e.data_type, l.data_type
FROM expected e
JOIN live l ON l.table_name = e.table_name AND l.column_name = e.column_name
WHERE e.data_type <> l.data_type
UNION ALL
SELECT 'EXTRA COLUMN', l.table_name, l.column_name, NULL, l.data_type
FROM live l
LEFT JOIN expected e ON e.table_name = l.table_name AND e.column_name = l.column_name
WHERE e.column_name IS NULL
  AND l.table_name IN (SELECT DISTINCT table_name FROM expected)
UNION ALL
SELECT 'EXTRA TABLE', t.table_name::text, NULL, NULL, NULL
FROM information_schema.tables t
WHERE t.table_schema = 'public' AND t.table_type = 'BASE TABLE'
  AND t.table_name::text NOT IN (SELECT table_name FROM expected)
ORDER BY 1, 2, 3;
